RESULTS = []


def check(spec, item, measured, limit, ok, bench_name):
    RESULTS.append(dict(spec=spec, item=item, measured=measured, limit=limit, ok=bool(ok), bench=bench_name))


def win(w, a, b):
    return (w["time"] >= a) & (w["time"] <= b)


def mean(w, sig, a, b):
    m = win(w, a, b)
    t, v = w["time"][m], w[sig][m]
    return float(np.trapezoid(v, t) / (t[-1] - t[0]))


def first(t, cond):
    k = np.flatnonzero(cond)
    return float(t[k[0]]) if len(k) else float("nan")


def settled_from(t, v, nom, band, t_end):
    """Time after which |v - nom| <= band*nom up to t_end."""
    m = t <= t_end
    bad = np.flatnonzero(np.abs(v[m] - nom) > band * nom)
    return float(t[m][bad[-1]]) if len(bad) else float(t[0])


