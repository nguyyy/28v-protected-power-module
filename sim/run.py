    fig, ax = figure(3, "ISO 16750-2 suppressed load dump: 58 V, 1 Ω, 400 ms (flat top, harsher than the standard)")
    x = ms(w)
    ax[0].plot(x, w["v(in)"], color=C[0], label="VIN (connector)")
