def an_bucks(w):
    t = w["time"]
    fig, ax = figure(3, "Load steps (25 → 100 % in 1 µs) and line ramps (16 ↔ 38 V) at full load", 1.8)
    for k, (rail, r) in enumerate(RAILS.items()):
        v = w[f"v(v{r['n']})"]
        pre, full, post = mean(w, f"v(v{r['n']})", 2.8e-3, 3e-3), mean(w, f"v(v{r['n']})", 3.4e-3, 3.5e-3), \
            mean(w, f"v(v{r['n']})", 3.6e-3, 3.7e-3)
        up, dn = win(w, 3e-3, 3.5e-3), win(w, 3.5e-3, 3.7e-3)
        dev = max(pre - v[up].min(), v[dn].max() - full) / r["v"]
        settle = max(settled_from(t[up], v[up], full, 0.01, 3.5e-3) - 3e-3, settled_from(t[dn], v[dn], post, 0.01, 3.7e-3) - 3.5e-3)
        check("Outputs", f"{rail} load step 25 → 100 % → 25 %", f"{dev * 100:.2f} %, settled in {settle * 1e6:.0f} µs",
              "< ± 5 %, < 200 µs", dev < 0.05 and settle < 200e-6, "bucks")
        ln = win(w, 3.75e-3, 5.2e-3)
        lo, hi = float(v[ln].min()), float(v[ln].max())
        ldev = max(hi - r["v"], r["v"] - lo) / r["v"]
        check("Outputs", f"{rail} across 16–38 V input at full load", f"{lo:.3f}–{hi:.3f} V ({ldev * 100:.2f} %)", "± 2 %",
              ldev <= 0.02, "bucks")
        ax[k].plot(ms(w), (v / r["v"] - 1) * 100, color=C[k], lw=1.0)
        limit(ax[k], 5, "+5 %"); limit(ax[k], -5, "−5 %")
        ax[k].set_ylim(-7, 7); ax[k].set_ylabel("% of nom.")
        ax[k].set_title(f"{rail}: worst deviation {dev * 100:.1f} % on the load step, settled in {settle * 1e6:.0f} µs")
    ax[2].plot(ms(w), w["v(vbus)"], color=C[3], label="VIN of the bucks")
    ax[2].set_ylabel("V"); ax[2].set_ylim(10, 42); ax[2].set_title("Input to the bucks")
    for a in ax:
        a.set_xlim(2.6, 5.2)
    ax[-1].set_xlabel("time (ms)")
    save(fig, "bucks")


def an_railshort(w):
    t = w["time"]
    fig, ax = figure(2, "Output short circuit, then release", 1.9)
    for k, (rail, r, t0) in enumerate((("5V0", RAILS["5V0"], 2.5e-3), ("3V3", RAILS["3V3"], 4.0e-3))):
        v, il = w[f"v(v{r['n']})"], w[f"i(l{r['n']})"]
        sc = win(w, t0 + 0.1e-3, t0 + 1e-3)
        ipk = float(il[sc].max())
        after = win(w, t0 + 1e-3, t0 + 2.5e-3)
        t_rec = settled_from(t[after], v[after], r["v"], 0.02, t0 + 2.5e-3) - (t0 + 1e-3)
        over = (float(v[after].max()) - r["v"]) / r["v"]
        # Spec only says "recovers on release". The peak on release is reported against 110 %,
        # which keeps a 3.3 V MCU under its 4.0 V absolute maximum.
        check("Outputs", f"{rail} short circuit and release",
              f"{ipk:.1f} A peak; recovers in {t_rec * 1e3:.2f} ms, peaks at {over * 100:+.0f} %",
              "recovers, peak ≤ 110 %", t_rec < 1.5e-3 and over <= 0.10, "railshort")
        ax[k].plot(ms(w), v, color=C[k], label=f"{rail} (V)")
        ax[k].plot(ms(w), il, color=C[2], lw=0.8, label="inductor current (A)")
        ax[k].set_ylabel("V  /  A"); ax[k].legend(loc="upper right")
        ax[k].axvspan(t0 * 1e3, (t0 + 1e-3) * 1e3, color=GRID, alpha=0.6, lw=0)
        ax[k].set_title(f"{rail} shorted for 1 ms (shaded): limit {ipk:.1f} A peak, recovers in {t_rec * 1e3:.2f} ms")
    ax[-1].set_xlabel("time (ms)")
    save(fig, "railshort")


