def pulse2a(ts):
    """ISO 7637-2 pulse 2a on top of the bus: +112 V, 1 us rise, decays to 10 % in 50 us."""
    return f"if(time<{ts},0,if(time<{ts}+1u,112*(time-{ts})/1u,112*exp(-(time-{ts}-1u)/21.7u)))"


