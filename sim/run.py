REUSE = False  # --reuse: re-analyse the existing .raw files instead of simulating


def simulate(name):
    cir = HERE / f"{name}.cir"
    t0 = time.time()
    if REUSE and cir.with_suffix(".raw").exists():
        return name, spice.read_raw(cir.with_suffix(".raw")), 0.0
    cir.write_text(netlist(name), encoding="utf-8")
    w = spice.run(cir)
    return name, w, time.time() - t0


def main(names):
    global REUSE
    REUSE = "--reuse" in names
    names = [n for n in names if n != "--reuse"] or list(BENCH)
    with ThreadPoolExecutor(max_workers=6) as ex:
        runs = list(ex.map(simulate, names))
    for name, w, dt in runs:
        print(f"{name:10s} simulated in {dt:5.1f} s, {len(w['time'])} points")
        ANALYSIS[name](w)
        del w
    path = HERE / "results.json"
    old = json.loads(path.read_text(encoding="utf-8")) if path.exists() and set(names) != set(BENCH) else []
    keep = [r for r in old if r["bench"] not in names]
    allr = keep + RESULTS
    order = list(BENCH)
    allr.sort(key=lambda r: order.index(r["bench"]))
    path.write_text(json.dumps(allr, indent=2, ensure_ascii=False), encoding="utf-8")
    rows = [r for r in allr if r["spec"] != "Stress"]
    md = ["| Area | Check | Simulated | Limit | |", "|---|---|---|---|---|"]
    md += [f"| {r['spec']} | {r['item']} | {r['measured']} | {r['limit']} | {'✅' if r['ok'] else '❌'} |" for r in rows]
    (HERE / "results.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(md))
    bad = [r for r in rows if not r["ok"]]
    print(f"\n{len(rows) - len(bad)}/{len(rows)} checks pass")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
